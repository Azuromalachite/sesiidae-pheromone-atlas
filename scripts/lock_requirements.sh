#!/usr/bin/env bash
# Resolve requirements.in into requirements.lock.txt in a fresh venv, so the
# lock holds exactly what a clean install gets (no stray local packages).
# Run with the Python CI uses (3.12).
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
python3 -m venv "$tmp/venv"
"$tmp/venv/bin/pip" install --quiet --upgrade pip
"$tmp/venv/bin/pip" install --quiet -r requirements.in
{
  echo "# Generated by scripts/lock_requirements.sh from requirements.in; do not edit."
  echo "# Python $("$tmp/venv/bin/python" -c 'import sys; print(".".join(map(str, sys.version_info[:3])))'), $(uname -s) $(uname -m)."
  "$tmp/venv/bin/pip" freeze --exclude-editable | LC_ALL=C sort -f
} > requirements.lock.txt
rm -rf "$tmp"
echo "wrote requirements.lock.txt"
