"""What does adding one compound to a lure do, across species and studies?

Reads only derived/tables/ (the Atlas's analytical form), never the YAML, so
it tests whether the tables are enough for a cross-paper question.

A *single-addition contrast* is a behavioural record whose treatment lure is
its comparator lure plus exactly one compound, in the same trap and
dispenser. For each, the added compound's share of the treatment lure is
computed when both lures use one unit. The report lists every contrast for
the compounds tested in more than one species, and sets the S. tenuis gland
chemistry from Japan and Korea beside the corresponding lure results.

    python analyses/added_compound_effects.py           # write analyses/added_compound_effects.md
    python analyses/added_compound_effects.py --check   # exit 1 if the committed report is stale
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T = ROOT / "derived" / "tables"
OUT = ROOT / "analyses" / "added_compound_effects.md"


def table(name):
    with open(T / f"{name}.tsv", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def build():
    obs = {r["observation_id"]: r for r in table("observations")}
    taxa = {r["taxon_id"]: r["accepted_name"] for r in table("taxa")}
    shorthand = {r["compound_id"]: r["shorthand"] for r in table("compounds")}
    assays = {r["observation_id"]: r for r in table("behavioural_assays")}
    setups = defaultdict(dict)
    for r in table("behavioural_setups"):
        setups[r["observation_id"]][r["role"]] = r
    lures = defaultdict(lambda: {"treatment": {}, "comparator": {}})
    for r in table("behavioural_stimuli"):
        lures[r["observation_id"]][r["role"]][r["compound_id"]] = r
    exps = defaultdict(list)
    for r in table("observation_experiments"):
        exps[r["observation_id"]].append(r["experiment_id"].removeprefix("spa.exp."))

    rows = []
    for oid, a in assays.items():
        t, c = lures[oid]["treatment"], lures[oid]["comparator"]
        if not c or set(c) - set(t) or len(set(t) - set(c)) != 1:
            continue
        if any(s.get("differs_from_treatment") == "true" for s in setups[oid].values()):
            continue  # a trap or dispenser contrast, not a compound one
        added = next(iter(set(t) - set(c)))
        same = all((t[k]["amount_value"], t[k]["amount_unit"]) == (c[k]["amount_value"], c[k]["amount_unit"]) for k in c)
        design = "addition" if same else "replacement"
        units = {r["amount_unit"] for r in t.values()}
        share = ""
        if len(units) == 1 and all(r["amount_value"] for r in t.values()):
            total = sum(float(r["amount_value"]) for r in t.values())
            share = f"{100 * float(t[added]['amount_value']) / total:.1f}" if total else ""
        o = obs[oid]
        rows.append({"added": added, "taxon": taxa[o["taxon_id"]], "population": o["population"] or o["locality"] or "",
                     "experiment": "; ".join(sorted(exps[oid])), "share": share, "effect": a["effect"],
                     "significance": a["significance"], "design": design, "measure": a["response_measure"], "base": " + ".join(sorted(shorthand[k] for k in c)),
                     "values": f"{a['treatment_value']} vs {a['comparator_value']}" if a["treatment_value"] else ""})

    by_added = defaultdict(list)
    for r in rows:
        by_added[r["added"]].append(r)
    multi = {k: v for k, v in by_added.items() if len({r["taxon"] for r in v}) > 1}

    L = ["# What does adding one compound to a lure do?", "",
         "Generated by `analyses/added_compound_effects.py` from `derived/tables/` only. Do not edit.", "",
         f"**{len(rows)} contrasts** whose treatment lure holds exactly one compound more than its comparator, in the same trap and dispenser, "
         f"across {len({r['taxon'] for r in rows})} species: {sum(r['design'] == 'addition' for r in rows)} are true **additions** "
         f"(every compound of the comparator at the same amount) and {sum(r['design'] == 'replacement' for r in rows)} are **replacements** "
         "(the base was reduced, usually to keep the total dose), which answer a different question.", "",
         f"{len(multi)} added compounds were tested in more than one species.", "",
         "`share` is the added compound's percentage of the treatment lure when both lures use one unit. "
         "`not_tested` means the source ran no test on that contrast; the effect is then the direction of the raw means.", ""]
    L += ["## Added compounds by number of contrasts", "",
          "| added compound | contrasts | of which additions | species | increased | decreased | no effect |", "|---|---|---|---|---|---|---|"]
    for k, v in sorted(by_added.items(), key=lambda kv: (-len(kv[1]), shorthand[kv[0]])):
        n = lambda e: sum(r["effect"] == e for r in v)
        L.append(f"| {shorthand[k]} | {len(v)} | {sum(r['design'] == 'addition' for r in v)} | {len({r['taxon'] for r in v})} "
                 f"| {n('increased')} | {n('decreased')} | {n('no_effect')} |")
    for k in sorted(multi, key=lambda k: shorthand[k]):
        L += ["", f"## {shorthand[k]} added", "", "| species | population | trial | design | base lure | share % | effect | significance | response (treatment vs comparator) |", "|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(multi[k], key=lambda r: (r["taxon"], r["population"], r["experiment"], float(r["share"] or 0))):
            measure = f" ({r['measure'].replace('_', ' ')})" if r["values"] and r["measure"] != "trap_catch" else ""
            L.append(f"| *{r['taxon']}* | {r['population']} | {r['experiment']} | {r['design']} | {r['base']} | {r['share']} "
                     f"| {r['effect']} | {r['significance']} | {r['values']}{measure} |")

    # S. tenuis: gland chemistry beside lure results, per source
    comps = table("chemical_components")
    tenuis = [o for o in obs.values() if taxa[o["taxon_id"]] == "Synanthedon tenuis"]
    L += ["", "## *S. tenuis*: female chemistry by source", "", "| source | population | Z3,Z13-18:OAc | Z3,Z13-18:OH |", "|---|---|---|---|"]
    for o in sorted(tenuis, key=lambda o: o["reference_id"]):
        if o["observation_type"] != "chemical_measurement":
            continue
        got = {c["compound_id"]: c["detected"] for c in comps if c["observation_id"] == o["observation_id"]}
        fmt = lambda cid: {"true": "detected", "false": "not detected"}.get(got.get(cid), "not tested")
        L.append(f"| {o['reference_id'].removeprefix('spa.ref.')} | {o['population']} | {fmt('spa.cmpd.z3_z13_18_oac')} | {fmt('spa.cmpd.z3_z13_18_oh')} |")
    L += ["", "Read with the `Z3,Z13-18:OAc added` and `Z3,Z13-18:OH added` sections above: each population's major gland compound is the other's antagonist.", ""]
    return "\n".join(L)


def main(argv=None):
    text = build()
    if "--check" in (argv if argv is not None else sys.argv[1:]):
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("analyses/added_compound_effects.md is stale: run python analyses/added_compound_effects.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
